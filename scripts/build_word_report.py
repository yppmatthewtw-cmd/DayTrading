def cjk(run, latin="Calibri"):
    """Set the run font so CJK glyphs resolve; creates rPr/rFonts if absent."""
    run.font.name = latin
    run._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "Microsoft JhengHei")
    return run

def H(t, lvl=1):
    h = doc.add_heading(t, level=lvl)
    for r in h.runs:
        r.font.color.rgb = RGBColor(0x1F, 0x38, 0x64)
        cjk(r)
    return h

def P(t, bold=False, size=10.5, italic=False, color=None):
    p = doc.add_paragraph()
    r = p.add_run(t); r.bold = bold; r.italic = italic; r.font.size = Pt(size)
    if color: r.font.color.rgb = color
    cjk(r)
    return p

def B(t):
    p = doc.add_paragraph(style="List Bullet")
    r = p.add_run(t); r.font.size = Pt(10.5)
    cjk(r)
    return p

def TBL(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ""
        r = c.paragraphs[0].add_run(h); r.bold = True; r.font.size = Pt(9.5)
        cjk(r)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(v)); r.font.size = Pt(9)
            cjk(r)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Inches(w)
    return t

